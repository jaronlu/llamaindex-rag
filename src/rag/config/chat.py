"""连续对话命令行的默认配置。

这些值只影响对话层：保留多少轮历史、历史回答进入改写提示词时截多长，以及
改写调用的输出上限。检索、重排和回答的算法参数仍由各自配置模块提供，避免
对话入口另造一套默认值。
"""

# 默认只把最近 3 轮问答交给改写模型：轮数越多，提示词和成本越高，也更早的
# 指代关系通常已经不重要。设为 0 可在命令行关闭上下文改写。
DEFAULT_CHAT_HISTORY_TURNS = 3

# 历史回答可能很长，进入改写提示词时截断到该字符数，避免单轮答案挤占上下文。
# 这只影响改写，不影响回答正文和证据展示。
DEFAULT_CHAT_CONTEXT_ANSWER_CHARS = 1200

# 改写只需要输出一个短问题；给 512 token 的余量，避免模型先输出解释再给问题。
DEFAULT_CHAT_CONDENSE_MAX_TOKENS = 512
DEFAULT_CHAT_CONDENSE_TEMPERATURE = 0.0
